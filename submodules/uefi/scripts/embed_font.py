#!/usr/bin/env python3
"""Embed printable ASCII from the standalone Developer Bold 12x24 BDF.

Usage: embed_font.py developer-bold.bdf SuperFbGraphicsFont.h
The BDF is an offline derivation input, never loaded by the firmware.
"""
import argparse
import hashlib
import re
from pathlib import Path


SOURCE_SHA256 = "78d4c1adf690b648f2fd4c86788cead69d8c91cd21a39505b876566cf50894df"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def field(block, name):
    match = re.search(rf"^{name} (.+)$", block, re.M)
    require(match is not None, f"Missing {name}")
    return match[1]


def glyphs(source):
    require(field(source, "FONTBOUNDINGBOX") == "12 24 0 -5", "Expected a 12x24 font cell")
    require(field(source, "FONT_ASCENT") == "19" and field(source, "FONT_DESCENT") == "5",
            "Expected ascent 19 and descent 5")
    result = {}
    for block in source.split("STARTCHAR ")[1:]:
        encoding = int(field(block, "ENCODING"))
        if not 32 <= encoding <= 126:
            continue
        advance = tuple(map(int, field(block, "DWIDTH").split()))
        width, height, left, bottom = map(int, field(block, "BBX").split())
        require(advance == (12, 0), f"U+{encoding:04X}: expected horizontal advance 12")
        top = 19 - bottom - height
        require(width > 0 and height > 0 and 0 <= left <= 12 - width and 0 <= top <= 24 - height,
                f"U+{encoding:04X}: bounding box lies outside the font cell")
        require("BITMAP\n" in block and "ENDCHAR" in block, f"U+{encoding:04X}: incomplete bitmap")
        bitmap = block.split("BITMAP\n", 1)[1].split("ENDCHAR", 1)[0].split()
        require(len(bitmap) == height, f"U+{encoding:04X}: wrong bitmap row count")
        row_bits = ((width + 7) // 8) * 8
        rows = [0] * 24
        for y, bits in enumerate(bitmap):
            require(len(bits) == row_bits // 4, f"U+{encoding:04X}: wrong bitmap row width")
            value = int(bits, 16)
            for x in range(width):
                if value & (1 << (row_bits - 1 - x)):
                    rows[top + y] |= 0x8000 >> (left + x)
        require(encoding not in result, f"Duplicate U+{encoding:04X}")
        result[encoding] = rows
    require(len(result) == 95, "Expected all 95 printable ASCII glyphs")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bdf", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        source = args.bdf.read_bytes()
        # Later Developer archives include other glyphs/licenses. Do not silently
        # substitute a different BDF while retaining this font's provenance.
        require(hashlib.sha256(source).hexdigest() == SOURCE_SHA256,
                "Expected the pinned standalone developer-bold.bdf (2007)")
        data = glyphs(source.decode("utf-8"))
        args.output.write_text(render_header(data), encoding="utf-8")
    except (ValueError, OSError) as error:
        parser.error(str(error))


def render_header(data):
    lines = [
        "/* Generated by scripts/embed_font.py from developer-bold.bdf.",
        " * Developer Bold 12x24 by Alex Efros (Powerman), declared Public Domain.",
        " * SPDX-License-Identifier: LicenseRef-Public-Domain",
        " * Source: https://powerman.name/download/font/developer-bold.bdf",
        " * Author's declaration: https://powerman.name/config/font.html",
        " * Uses the standalone 2007 BDF, not the later GPL Developer bundle.",
        " */",
        "#ifndef SUPER_FB_GRAPHICS_FONT_H",
        "#define SUPER_FB_GRAPHICS_FONT_H",
        "#define SFB_FONT_WIDTH 12",
        "#define SFB_FONT_HEIGHT 24",
        "/* Each 12-bit row is left-aligned, most significant pixel first. */",
        "STATIC CONST UINT16 mSfbFont[95][SFB_FONT_HEIGHT] = {",
    ]
    for code in range(32, 127):
        lines.append("  {" + ",".join(f"0x{v:04X}" for v in data[code]) + f"}}, /* U+{code:04X} */")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
